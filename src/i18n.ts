const LOCALES: Record<Locale, Record<string, string>> = { zh: ZH, en: EN };

let currentLocale: Locale = (localStorage.getItem("beeapi-locale") as Locale) || "zh";

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(l: Locale) {
  currentLocale = l;
  localStorage.setItem("beeapi-locale", l);
}

export function t(key: string, params?: Record<string, string | number>): string {
  let str = LOCALES[currentLocale]?.[key] ?? LOCALES.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}
